-- Schema export. READ-ONLY: only SELECTs, changes nothing.
--
-- Prints the SQL that recreates the whole public schema as it exists in the database right now
-- (core, plant database and camera tables together):
-- tables, constraints, indexes, row-level security, policies, functions (with their grants),
-- triggers, and the reference rows (hardware types, environment contexts, and the hand-verified
-- plants with their hardware requirements).
--
-- Use: paste into the Supabase SQL editor and run. The result is ONE cell holding the whole
-- script. Copy that cell and save it as supabase/sql/live_schema_snapshot.sql.
--
-- Not included: imported plants (pn-*, recreate them with import_perenual.py), your own nodes,
-- zones, logs and users, and Supabase's built-in table grants.
--
-- The script it prints is a record of the schema, written for reading and for a fresh project.
-- Constraints and RLS are added after the tables, so statements may need re-ordering to run
-- cleanly on an empty database; it uses plain "create table", not "if not exists".

with
t as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
cols as (
  select t.relname,
         string_agg(
           format('  %I %s%s%s%s',
                  a.attname,
                  format_type(a.atttypid, a.atttypmod),
                  case a.attidentity when 'a' then ' generated always as identity'
                                     when 'd' then ' generated by default as identity' else '' end,
                  case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                       when a.attidentity = '' and ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                       else '' end,
                  case when a.attnotnull then ' not null' else '' end),
           E',\n' order by a.attnum) as body
  from t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  group by t.relname
),
parts as (
  -- 1. tables
  select 100 as ord, t.relname as k,
         format(E'create table public.%I (\n%s\n);', t.relname, cols.body) as sql
  from t join cols using (relname)

  union all
  -- 2. constraints: primary key and unique and check first, foreign keys last
  select case co.contype when 'f' then 300 else 200 end, t.relname || co.conname,
         format('alter table only public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from t join pg_constraint co on co.conrelid = t.oid
  where co.contype in ('p', 'u', 'c', 'f', 'x')

  union all
  -- 3. indexes that are not behind a constraint
  select 400, i.indexname, pg_get_indexdef(ix.indexrelid) || ';'
  from pg_indexes i
  join pg_class ic on ic.relname = i.indexname
  join pg_namespace icn on icn.oid = ic.relnamespace and icn.nspname = i.schemaname
  join pg_index ix on ix.indexrelid = ic.oid
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint co where co.conindid = ix.indexrelid)

  union all
  -- 4. row-level security
  select 500, t.relname,
         format('alter table public.%I enable row level security;', t.relname)
         || case when t.relforcerowsecurity then format(E'\nalter table public.%I force row level security;', t.relname) else '' end
  from t where t.relrowsecurity

  union all
  -- 5. policies on public tables
  select 600, p.tablename || p.policyname,
         format('create policy %I on public.%I as %s for %s%s%s%s;',
                p.policyname, p.tablename, lower(p.permissive), lower(p.cmd),
                case when p.roles = '{public}' then '' else ' to ' || array_to_string(p.roles, ', ') end,
                case when p.qual is not null then E'\n  using (' || p.qual || ')' else '' end,
                case when p.with_check is not null then E'\n  with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname = 'public'

  union all
  -- 5b. policies on storage.objects (photo access lives here)
  select 650, p.policyname,
         format('create policy %I on storage.objects as %s for %s%s%s%s;',
                p.policyname, lower(p.permissive), lower(p.cmd),
                case when p.roles = '{public}' then '' else ' to ' || array_to_string(p.roles, ', ') end,
                case when p.qual is not null then E'\n  using (' || p.qual || ')' else '' end,
                case when p.with_check is not null then E'\n  with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname = 'storage' and p.tablename = 'objects'

  union all
  -- 5c. storage buckets
  select 640, b.id,
         format('insert into storage.buckets (id, name, public) values (%L, %L, %s) on conflict (id) do nothing;',
                b.id, b.name, case when b.public then 'true' else 'false' end)
  from storage.buckets b

  union all
  -- 6. functions in public (not from extensions), then who may run them
  select 250, p.oid::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  union all
  select 251, p.oid::text,
         format('revoke all on function public.%I(%s) from public;', p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    and not exists (select 1 from aclexplode(p.proacl) a where a.grantee = 0 and a.privilege_type = 'EXECUTE')

  union all
  select 252, p.oid::text || a.grantee::text,
         format('grant execute on function public.%I(%s) to %s;',
                p.proname, pg_get_function_identity_arguments(p.oid),
                case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee)::text end)
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  cross join lateral aclexplode(p.proacl) a
  where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
    and a.privilege_type = 'EXECUTE'
    and (a.grantee = 0 or a.grantee in (select oid from pg_roles where rolname in ('anon', 'authenticated', 'service_role')))
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  union all
  -- 7. triggers on public tables
  select 800, tg.tgname || tg.tgrelid::text, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg
  join t on t.oid = tg.tgrelid
  where not tg.tgisinternal

  union all
  -- 8. views
  select 900, c.relname,
         format(E'create view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'

  union all
  -- 9. reference rows (written as inserts that skip rows that already exist)
  select 1000, 'hardware_types',
         format('insert into public.hardware_types select * from json_populate_recordset(null::public.hardware_types, %L) on conflict do nothing;',
                (select coalesce(json_agg(x order by x.id), '[]'::json) from public.hardware_types x)::text)
  union all
  select 1010, 'environment_contexts',
         format('insert into public.environment_contexts select * from json_populate_recordset(null::public.environment_contexts, %L) on conflict do nothing;',
                (select coalesce(json_agg(x order by x.id), '[]'::json) from public.environment_contexts x)::text)
  union all
  select 1020, 'plant_profiles',
         format('insert into public.plant_profiles select * from json_populate_recordset(null::public.plant_profiles, %L) on conflict do nothing;',
                (select coalesce(json_agg(x order by x.id), '[]'::json) from public.plant_profiles x where x.confidence = 'verified')::text)
  union all
  select 1030, 'plant_hardware_requirements',
         format('insert into public.plant_hardware_requirements select * from json_populate_recordset(null::public.plant_hardware_requirements, %L) on conflict do nothing;',
                (select coalesce(json_agg(x order by x.plant_id, x.hardware_type_id), '[]'::json)
                   from public.plant_hardware_requirements x
                  where x.plant_id in (select id from public.plant_profiles where confidence = 'verified'))::text)
)
select '-- Exported from the live database on ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD')
       || E' by supabase/sql/export_schema.sql\n\n'
       || string_agg(sql, E'\n\n' order by ord, k) as script
from parts;
